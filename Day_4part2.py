# some math functions by importing :: 

import math

pi = math.pi
print(pi)

e = math.e          # exponential 
print(e)


x = 9
sq = math.sqrt(x)      # square root
print(sq)

y = 2.23
celling = math.ceil(y)     #celling function(rounding up always)
print(celling) 

z = 6.69
fl = math.floor(z)  #floor function (always rounding down)
print(fl) 
